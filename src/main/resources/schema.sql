CREATE TABLE IF NOT EXISTS genre (
    id int PRIMARY KEY,
    title varchar(40)
);

CREATE TABLE IF NOT EXISTS mpa (
    id int PRIMARY KEY,
    code varchar(10) UNIQUE ,
    description varchar
);

CREATE TABLE IF NOT EXISTS films (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(40) NOT NULL,
    description varchar(200),
    release_date date NOT NULL,
    duration int,
    mpa_id int REFERENCES mpa(id) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS film_genre(
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    film_id int NOT NULL  REFERENCES films(id) ON DELETE CASCADE ON UPDATE CASCADE,
    genre_id int NOT NULL  REFERENCES genre(id) ON DELETE CASCADE ON UPDATE CASCADE,
    UNIQUE (film_id, genre_id)
);

CREATE TABLE IF NOT EXISTS users (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login varchar UNIQUE NOT NULL,
    name varchar,
    email varchar UNIQUE NOT NULL,
    birthday date
);

CREATE TABLE IF NOT EXISTS user_link (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id_from int NOT NULL REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    user_id_to int NOT NULL REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    UNIQUE (user_id_from, user_id_to)
);

CREATE TABLE IF NOT EXISTS likes (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    film_id int NOT NULL REFERENCES films(id) ON DELETE CASCADE ON UPDATE CASCADE,
    user_id int NOT NULL REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    UNIQUE (film_id, user_id)
);

